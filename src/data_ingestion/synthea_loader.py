"""
Synthea Data Loader
Loads synthetic patient data generated by Synthea
"""
import os
import pandas as pd
from pathlib import Path
from typing import Dict, Any, Optional
import zipfile


class SyntheaDataLoader:
    """Loader for Synthea synthetic patient data"""

    def __init__(self, config: Dict[str, Any]):
        self.config = config
        project_root = Path(__file__).resolve().parents[2]
        self.data_dir = Path(config.get("data_dir", "data/synthea")).expanduser()
        if not self.data_dir.is_absolute():
            self.data_dir = project_root / self.data_dir

        data_directories = (
            self.data_dir,
            project_root / "data" / "data" / "synthea",
            project_root / "output" / "csv",
            project_root / "data" / "output" / "csv",
        )
        self.data_dir = next(
            (directory for directory in data_directories
             if (directory / "patients.csv").is_file()),
            self.data_dir,
        )
        self.patient_count = config.get("patient_count", 1000)

    def download_synthea(self) -> Path:
        """Download or locate Synthea data"""
        self.data_dir.mkdir(parents=True, exist_ok=True)

        # Check if data already exists
        patients_file = self.data_dir / "patients.csv"
        if patients_file.exists():
            print(f"✓ Synthea data found at {self.data_dir}")
            return self.data_dir

        print("Synthea data not found. Please generate using:")
        print("1. Download Synthea: https://github.com/synthetichealth/synthea")
        print("2. Run: java -jar synthea-with-dependencies.jar -p {self.patient_count}")
        print("3. Copy output files to {self.data_dir}")

        return self.data_dir

    def load_patients(self) -> pd.DataFrame:
        """Load patient demographics"""
        patients_file = self.data_dir / "patients.csv"
        if not patients_file.exists():
            raise FileNotFoundError(
                f"Patients file not found at {patients_file}. "
                "Please run download_synthea() first."
            )
        return pd.read_csv(patients_file)

    def load_observations(self) -> pd.DataFrame:
        """Load patient observations/vitals"""
        obs_file = self.data_dir / "observations.csv"
        if obs_file.exists():
            return pd.read_csv(obs_file)
        return pd.DataFrame()

    def load_conditions(self) -> pd.DataFrame:
        """Load patient conditions"""
        cond_file = self.data_dir / "conditions.csv"
        if cond_file.exists():
            return pd.read_csv(cond_file)
        return pd.DataFrame()

    def load_medications(self) -> pd.DataFrame:
        """Load patient medications"""
        med_file = self.data_dir / "medications.csv"
        if med_file.exists():
            return pd.read_csv(med_file)
        return pd.DataFrame()

    def load_fhir_bundle(self) -> Optional[Dict]:
        """Load FHIR bundle if available"""
        fhir_dir = self.data_dir / "fhir"
        if fhir_dir.exists():
            # Load first FHIR file as example
            fhir_files = list(fhir_dir.glob("*.json"))
            if fhir_files:
                import json
                with open(fhir_files[0], 'r') as f:
                    return json.load(f)
        return None

    def get_summary(self) -> Dict[str, Any]:
        """Get summary statistics of the dataset"""
        patients = self.load_patients()
        observations = self.load_observations()
        conditions = self.load_conditions()

        return {
            "dataset_type": "Synthea",
            "total_patients": len(patients),
            "total_observations": len(observations),
            "total_conditions": len(conditions),
            "columns": {
                "patients": list(patients.columns),
                "observations": list(observations.columns) if not observations.empty else [],
                "conditions": list(conditions.columns) if not conditions.empty else []
            }
        }